"""Explicit configuration-only operations; firmware installation stays immutable."""
from __future__ import annotations

import hashlib
import json
import os
from pathlib import Path
import re
import time

from core.exceptions import GenerationError, WizardExit
from core.firmware_workflow import (
    FirmwareWorkflowError, FirmwareWorkflowState, checkpoint_path,
    checkpoint_revision, load_checkpoint, restore_wizard_data,
)
from core.reconciler import write_text_atomically
from core.workflow_outcome import WorkflowOutcome, cancelled, failed
from core.workspace import exclusive_file_lock

SCHEMA = "kace-configuration-operation/v1"


def _digest(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def run_configuration_operation(operation_id, checkpoint_sha256, *, resume=False, result_sha256=None):
    """Regenerate saved decisions and request review; never install or flash.

    Resume retains generated bytes, but requires a new preflight and approval.
    Only the shared transaction can attest activation; an old COMPLETE is not
    the result of this operation. The firmware checkpoint lock is held through
    publication and its exact bytes are rechecked by the publication validator.
    """
    if not re.fullmatch(r"[0-9a-f]{32}", str(operation_id)) or not re.fullmatch(
        r"[0-9a-f]{64}", str(checkpoint_sha256)
    ):
        return failed(WorkflowOutcome.PRECONDITION_FAILED, "Invalid configuration operation identity.")
    if os.environ.get("KACE_AUTO") == "1":
        return failed(WorkflowOutcome.PRECONDITION_FAILED, "New configuration requires explicit interactive approval.")
    if (resume and not re.fullmatch(r"[0-9a-f]{64}", str(result_sha256))) or (not resume and result_sha256 is not None):
        return failed(WorkflowOutcome.PRECONDITION_FAILED, "Resume requires the exact configuration result hash.")

    source = checkpoint_path()
    directory = Path(source).parent / "configuration-operations" / operation_id
    receipt = None
    generated_manifest_sha256 = None

    def guard_checkpoint():
        from core.config_transaction import ConfigConflictError
        if checkpoint_revision(source)[1] != checkpoint_sha256:
            raise ConfigConflictError("Original firmware checkpoint changed; configuration operation stopped.")

    def emit(state, detail, *, exit_code=None):
        nonlocal receipt
        receipt = {
            "schema": SCHEMA, "operation_id": operation_id,
            "source_checkpoint_sha256": checkpoint_sha256,
            "sequence": (receipt or {}).get("sequence", 0) + 1,
            "state": state, "detail": str(detail), "exit_code": exit_code,
            "generated_manifest_sha256": generated_manifest_sha256,
            "updated_at": int(time.time()),
        }
        write_text_atomically(str(directory / "result.json"), json.dumps(receipt, sort_keys=True) + "\n")
        from core.moonraker_deployer import JsonEventSink
        JsonEventSink()({
            "schema": 1, "workflow_kind": "configuration",
            "workflow_id": "configuration-" + operation_id,
            "sequence": receipt["sequence"], "state": state, "detail": str(detail),
        })

    def finish(result):
        state = "COMPLETE" if result.ok else (
            "CANCELLED" if result.outcome is WorkflowOutcome.CANCELLED else
            "PENDING_ACTIVATION" if result.outcome is WorkflowOutcome.DEPLOYED_PENDING_ACTIVATION else "FAILED"
        )
        emit(state, result.detail, exit_code=result.exit_code)
        return result

    try:
        with exclusive_file_lock(source + ".lock", timeout_seconds=1):
            guard_checkpoint()
            checkpoint = load_checkpoint(source, verify_artifact=True)
            if checkpoint is None or checkpoint["state"] != FirmwareWorkflowState.COMPLETE.value:
                raise FirmwareWorkflowError("A validated COMPLETE installation is required; use installation recovery for pending work.")
            user_data = restore_wizard_data(checkpoint.get("wizard_data") or {})
            parsed_data = user_data.get("board_parsed")
            if not parsed_data:
                raise FirmwareWorkflowError("Saved board configuration is missing; configuration-only regeneration cannot fetch a replacement.")
            user_data["workflow_checkpoint"] = checkpoint
            from core.translations import set_lang, set_mode
            set_lang(user_data.get("language", user_data.get("lang", "English")))
            set_mode(user_data.get("mode", "Beginner"))

            if resume:
                if _digest(directory / "result.json") != result_sha256:
                    raise FirmwareWorkflowError("Configuration result changed before resume.")
                saved = json.loads((directory / "result.json").read_text(encoding="utf-8"))
                if (not isinstance(saved, dict) or saved.get("schema") != SCHEMA or saved.get("operation_id") != operation_id
                        or saved.get("source_checkpoint_sha256") != checkpoint_sha256
                        or type(saved.get("sequence")) is not int or saved["sequence"] < 1
                        or saved.get("state") == "COMPLETE"):
                    raise FirmwareWorkflowError("Configuration operation cannot be resumed from this receipt.")
                generated_manifest_sha256 = saved.get("generated_manifest_sha256")
                if (not re.fullmatch(r"[0-9a-f]{64}", str(generated_manifest_sha256))
                        or _digest(directory / "generated.json") != generated_manifest_sha256):
                    raise FirmwareWorkflowError("Generated manifest changed or was not committed; configuration cannot resume.")
                receipt = saved
            else:
                directory.mkdir(parents=True, exist_ok=False)
            emit("PREPARING", "Resuming configuration review" if resume else "Generating configuration from saved installation decisions")

            try:
                from core.generator import generate_config
                from core.wizard.steps.probe_homing import validate_wizard_probe_homing_geometry
                from core.wizard.steps.thermal import review_thermal_policy
                validate_wizard_probe_homing_geometry(user_data)
                generated_path = directory / "printer.cfg"
                if not resume:
                    review_thermal_policy(parsed_data, user_data, include_macros=bool(user_data.get("macros_generated")))
                    generate_config(parsed_data, user_data, output_path=str(generated_path),
                                    include_macros=bool(user_data.get("macros_generated")))
                    names = ["printer.cfg", "printer.cfg.provenance.json"]
                    if user_data.get("macros_generated"):
                        names.append("macros.cfg")
                    manifest = {name: _digest(directory / name) for name in names}
                    write_text_atomically(str(directory / "generated.json"), json.dumps(manifest, sort_keys=True) + "\n")
                    generated_manifest_sha256 = _digest(directory / "generated.json")
                    emit("PREPARING", "Generated configuration manifest committed; preparing effective review")
                manifest = json.loads((directory / "generated.json").read_text(encoding="utf-8"))
                expected_names = {"printer.cfg", "printer.cfg.provenance.json"}
                if user_data.get("macros_generated"):
                    expected_names.add("macros.cfg")
                if not isinstance(manifest, dict) or set(manifest) != expected_names or any(_digest(directory / name) != digest for name, digest in manifest.items()):
                    raise FirmwareWorkflowError("Generated configuration changed; interrupted operation cannot reuse it.")
                from core.firmware_workflow import extract_mcu_serial
                serial = extract_mcu_serial(str(generated_path))
                if not serial or serial != checkpoint["hardware"].get("verified_serial_path"):
                    raise FirmwareWorkflowError("Generated [mcu].serial does not match the verified installation MCU.")
                guard_checkpoint()
                from core.config_transaction import configuration_transport
                from core.deployer import _run_config_transaction, _select_config_activation
                transport = configuration_transport("127.0.0.1", 7125)
                if not transport.supports_conditional_write(b""):
                    raise FirmwareWorkflowError("Local conditional publication is unavailable.")
                generated = (str(generated_path), generated_path.read_bytes(),
                             (directory / "macros.cfg").read_bytes() if user_data.get("macros_generated") else None)
                def record_transaction(transaction, result):
                    from core.klipper_preflight import plan_digest
                    plan = transaction.plan
                    data = {
                        "operation_id": operation_id,
                        "source_checkpoint_sha256": checkpoint_sha256,
                        "transaction_id": result.transaction_id,
                        "state": result.state.name, "detail": result.detail,
                        "plan_digest": plan_digest(plan) if plan is not None else None,
                        "changed_files": [item.remote_name for item in plan.changed_artifacts] if plan is not None else [],
                        "artifacts": {item.remote_name: hashlib.sha256(item.content).hexdigest() for item in plan.artifacts} if plan is not None else {},
                        "activation": transaction.activation,
                        "snapshot_path": result.snapshot.storage_path if result.snapshot is not None else None,
                        "rollback_succeeded": result.rollback_succeeded,
                    }
                    write_text_atomically(str(directory / ("transaction-" + result.transaction_id + ".json")), json.dumps(data, sort_keys=True) + "\n")
                # The existing transaction performs effective-tree Docker preflight,
                # interactive diff approval, snapshots, activation and firmware proof.
                result = _run_config_transaction(
                    transport, user_data, "none", generated,
                    activation_selector=_select_config_activation,
                    operation_sink=emit, snapshot_root=str(directory / "snapshots"),
                    checkpoint_guard=guard_checkpoint,
                    operation_record=record_transaction,
                    allow_existing_activation=resume,
                    preserve_moonraker=True,
                )
                guard_checkpoint()
                return finish(result)
            except (WizardExit, KeyboardInterrupt, EOFError):
                return finish(cancelled("Configuration operation cancelled; existing installation checkpoint preserved."))
            except (OSError, ValueError, RuntimeError, FirmwareWorkflowError, GenerationError) as exc:
                return finish(failed(WorkflowOutcome.PRECONDITION_FAILED, str(exc)))
    except (OSError, ValueError, RuntimeError, FirmwareWorkflowError, TimeoutError) as exc:
        # Never overwrite an existing operation (including its COMPLETE receipt)
        # when admission fails, and never change the installation checkpoint.
        return failed(WorkflowOutcome.PRECONDITION_FAILED, str(exc))
