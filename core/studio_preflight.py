"""Session-bound preflight client for Studio's authenticated SSH reverse tunnel.

Only reviewed bytes and validation results cross the tunnel. This client does
not write configuration, launch Docker, or accept a host supplied by environment.
The authenticated SSH session and its short-lived token establish the validator
authority; the receipt is not a physical or target-runtime attestation.
"""
from __future__ import annotations

import base64
from hashlib import sha256
import hmac
import json
import os
from pathlib import PurePosixPath
import re
import socket
import time
import uuid


SCHEMA = "kace-studio-preflight/v2"
PORT_ENV = "KACE_STUDIO_PREFLIGHT_PORT"
TOKEN_ENV = "KACE_STUDIO_PREFLIGHT_TOKEN"
SESSION_ENV = "KACE_STUDIO_PREFLIGHT_SESSION"
MAX_REQUEST_BYTES = 32 * 1024 * 1024
MAX_RESPONSE_BYTES = 64 * 1024
MAX_FILES = 128
MAX_CONTENT_BYTES = 16 * 1024 * 1024
TIMEOUT_SECONDS = 150.0
IDENTITY_FIELDS = ("pin", "engine_sha256", "dockerfile_sha256", "worker_sha256")
_HEX32 = re.compile(r"[0-9a-f]{32}\Z")
_HEX40 = re.compile(r"[0-9a-f]{40}\Z")
_HEX64 = re.compile(r"[0-9a-f]{64}\Z")


class _ProtocolError(ValueError):
    """A bounded, credential-free diagnostic generated by this client."""


def configured():
    """Partial/empty Studio configuration must fail closed, not select Docker."""
    return any(name in os.environ for name in (PORT_ENV, TOKEN_ENV, SESSION_ENV))


def _remaining(deadline):
    remaining = deadline - time.monotonic()
    if remaining <= 0:
        raise TimeoutError("Studio validation deadline expired")
    return remaining


def _receive_exact(connection, size, deadline):
    chunks = bytearray()
    while len(chunks) < size:
        connection.settimeout(_remaining(deadline))
        chunk = connection.recv(size - len(chunks))
        if not chunk:
            raise _ProtocolError("Studio disconnected before returning a complete result")
        chunks.extend(chunk)
    _remaining(deadline)
    return bytes(chunks)


def _unique_object(pairs):
    result = {}
    for key, value in pairs:
        if key in result:
            raise _ProtocolError("Studio returned duplicate JSON fields")
        result[key] = value
    return result


def _reject_constant(_value):
    raise _ProtocolError("Studio returned a non-finite JSON value")


def _auth(payload, token, domain):
    """Authenticate canonical JSON with direction separation; never send the key."""
    canonical = json.dumps(payload, sort_keys=True, separators=(",", ":"),
                           ensure_ascii=True, allow_nan=False).encode("utf-8")
    return hmac.new(bytes.fromhex(token), domain + canonical, sha256).hexdigest()


def _files_payload(files, tree_digest):
    if not isinstance(files, dict) or not 1 <= len(files) <= MAX_FILES or "printer.cfg" not in files:
        raise _ProtocolError("Studio validation requires a bounded configuration tree with printer.cfg")
    total = 0
    for name, content in files.items():
        if not isinstance(name, str) or not isinstance(content, bytes):
            raise _ProtocolError("Configuration paths must be strings and content must be bytes")
        path = PurePosixPath(name)
        if (not name or path.is_absolute() or name != path.as_posix()
                or "\\" in name or ":" in name or any(ord(c) < 32 for c in name)
                or any(part in ("", ".", "..") for part in name.split("/"))):
            raise _ProtocolError("Configuration tree contains an unsafe path")
        if any(parent.as_posix() in files for parent in path.parents if str(parent) != "."):
            raise _ProtocolError("Configuration tree contains a file/directory collision")
        total += len(content)
        if total > MAX_CONTENT_BYTES:
            raise _ProtocolError("Configuration tree exceeds the Studio validation size limit")
    digest = sha256()
    payload = []
    for name, content in sorted(files.items()):
        encoded = name.encode("utf-8")
        digest.update(len(encoded).to_bytes(8, "big"))
        digest.update(encoded)
        digest.update(sha256(content).digest())
        payload.append({"path": name, "content_base64": base64.b64encode(content).decode("ascii")})
    if not isinstance(tree_digest, str) or not _HEX64.fullmatch(tree_digest) or digest.hexdigest() != tree_digest:
        raise _ProtocolError("Configuration tree does not match the requested digest")
    return payload


def validate_files(files, identity, tree_digest):
    """Return valid/invalid/unverified; only an exact session receipt is accepted.

    The caller must recheck the plan digest and destination immediately before
    publication. Once Studio is selected, failures never fall back to local Docker.
    """
    deadline = time.monotonic() + TIMEOUT_SECONDS
    fallback_digest = tree_digest if isinstance(tree_digest, str) and _HEX64.fullmatch(tree_digest) else ""
    token = ""
    try:
        port = os.environ.get(PORT_ENV, "")
        token = os.environ.get(TOKEN_ENV, "")
        session = os.environ.get(SESSION_ENV, "")
        if (not re.fullmatch(r"[1-9][0-9]{0,4}", port) or int(port) > 65535
                or not _HEX64.fullmatch(token) or not _HEX32.fullmatch(session)):
            raise _ProtocolError("Studio preflight session is missing or malformed; reconnect and launch through Studio")
        if not isinstance(identity, dict) or set(identity) != set(IDENTITY_FIELDS):
            raise _ProtocolError("Studio validator identity is incomplete")
        for key in IDENTITY_FIELDS:
            value = identity[key]
            pattern = _HEX40 if key == "pin" else _HEX64
            if not isinstance(value, str) or not pattern.fullmatch(value):
                raise _ProtocolError("Studio validator identity is malformed")
        request = {
            "schema": SCHEMA, "session": session,
            "request_id": uuid.uuid4().hex, **identity, "tree_digest": tree_digest,
            "files": _files_payload(files, tree_digest),
        }
        request["auth"] = _auth(request, token, b"request\0")
        encoded = json.dumps(request, separators=(",", ":"), ensure_ascii=True, allow_nan=False).encode("utf-8")
        if len(encoded) > MAX_REQUEST_BYTES:
            raise _ProtocolError("Studio validation request exceeds the protocol size limit")
        with socket.create_connection(("127.0.0.1", int(port)), timeout=_remaining(deadline)) as connection:
            connection.settimeout(_remaining(deadline))
            connection.sendall(len(encoded).to_bytes(4, "big") + encoded)
            size = int.from_bytes(_receive_exact(connection, 4, deadline), "big")
            if not 0 < size <= MAX_RESPONSE_BYTES:
                raise _ProtocolError("Studio validation response exceeds the protocol size limit")
            raw = _receive_exact(connection, size, deadline)
        result = json.loads(raw.decode("utf-8"), object_pairs_hook=_unique_object, parse_constant=_reject_constant)
        expected_fields = {"schema", "session", "request_id", *IDENTITY_FIELDS, "tree_digest", "status", "detail", "auth"}
        if not isinstance(result, dict) or set(result) != expected_fields:
            raise _ProtocolError("Studio validation response has an unexpected schema")
        authenticator = result["auth"]
        if (not isinstance(authenticator, str) or not _HEX64.fullmatch(authenticator)
                or not hmac.compare_digest(authenticator, _auth(
                    {key: value for key, value in result.items() if key != "auth"}, token, b"response\0"))):
            raise _ProtocolError("Studio validation response could not be authenticated")
        for key in expected_fields - {"status", "detail", "auth"}:
            if not isinstance(result[key], str) or result[key] != request[key]:
                raise _ProtocolError("Studio validation response does not match this session, request, tree or validator")
        if result["status"] not in ("valid", "invalid", "unverified") or not isinstance(result["status"], str):
            raise _ProtocolError("Studio returned an unknown validation status")
        if not isinstance(result["detail"], str) or len(result["detail"]) > 4096:
            raise _ProtocolError("Studio returned an invalid validation diagnostic")
        _remaining(deadline)
        return {"status": result["status"], "detail": result["detail"].replace(token, "[redacted]"), "tree_digest": tree_digest}
    except _ProtocolError as exc:
        detail = str(exc)
    except TimeoutError:
        detail = "Studio preflight timed out; configuration was not validated"
    except (OSError, UnicodeError, ValueError, TypeError, RecursionError):
        # Socket/server exceptions can contain credentials or attacker-controlled
        # bytes. Only the deliberately bounded diagnostics above are surfaced.
        detail = "Studio preflight connection or response is unavailable; configuration was not validated"
    return {"status": "unverified", "detail": detail, "tree_digest": fallback_digest}
